#!/usr/bin/env python3
"""Exact G0 column lookup using a short ROM plus xorshift linear jumps.

Only the fixed PBCH(t=8,l=13,seed=62) matrix is targeted.  The ROM contains
32-bit xorshift states at block boundaries; conditional linear maps advance
to the requested position.  Prefix and BCH-parity columns remain literal.
This changes neither the code matrix nor any FWHT search score.
"""

from collections import Counter
from functools import reduce
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from model.ecc import STUDY_PROFILES  # noqa: E402

OUT = Path(__file__).resolve().parent
CODEC = STUDY_PROFILES["pbch_paper"]


def xs(value):
    value ^= (value << 13) & 0xffffffff
    value ^= value >> 17
    value ^= (value << 5) & 0xffffffff
    return value


def apply_columns(columns, value):
    return reduce(int.__xor__,
                  (columns[bit] for bit in range(32) if value >> bit & 1), 0)


def xor_cse(rows):
    """Share repeated XOR pairs in a constant binary linear transform."""
    terms = [set(bit for bit in range(32) if row >> bit & 1) for row in rows]
    pairs_out = []
    while True:
        counts = Counter()
        for term in terms:
            order = sorted(term)
            for left, bit in enumerate(order):
                for other in order[left + 1:]:
                    counts[bit, other] += 1
        if not counts:
            break
        pair, count = min(counts.items(), key=lambda item: (-item[1], item[0]))
        if count < 2:
            break
        new_index = 32 + len(pairs_out)
        pairs_out.append(pair)
        for term in terms:
            if pair[0] in term and pair[1] in term:
                term.difference_update(pair)
                term.add(new_index)
    return pairs_out, [sorted(term) for term in terms]


def hex_literal(width, value):
    return "%d'h%0*x" % (width, (width + 3) // 4, value)


def packed(values, width):
    return sum(value << (width * index) for index, value in enumerate(values))


def generate(block, columns, reverse=False):
    low_bits = (block - 1).bit_length()
    suffix = "%d%s" % (block, "r" if reverse else "")
    states = []
    state = CODEC.mask_seed
    expected_payload = CODEC.mask_columns()
    for position in range(CODEC.k):
        state = xs(state)
        assert state & 8191 == expected_payload[position], \
            "Zero-column replacement must be handled for another matrix seed"
        if position % block == 0:
            states.append(state)

    parity = columns[CODEC.l + CODEC.k:]
    lines = [
        "`default_nettype none",
        "// Generated by gen_scan_labels.py; exact frozen PBCH paper matrix.",
        "module pbch_scan_label_b%s (" % suffix,
        "    input wire [12:0] position_i,",
        "    output reg [12:0] label_o",
        ");",
        "    localparam [%d:0] STATE_ROM = %s;" %
        (len(states) * 32 - 1, hex_literal(len(states) * 32, packed(states, 32))),
        "    localparam [%d:0] PARITY_ROM = %s;" %
        (len(parity) * 13 - 1, hex_literal(len(parity) * 13, packed(parity, 13))),
        "    wire [12:0] payload_position = position_i - 13'd13;",
        "    wire [%d:0] block_index = payload_position[11:%d];" %
        (12 - low_bits - 1, low_bits),
        "    wire [%d:0] lane_index = payload_position[%d:0];" %
        (low_bits - 1, low_bits - 1),
        "    wire [6:0] parity_index = position_i - 13'd4109;",
        "    wire [31:0] state_0 = STATE_ROM[block_index*32 +: 32];",
    ]
    maps = [xs(1 << bit) for bit in range(32)]
    all_maps = []
    for _ in range(low_bits):
        all_maps.append(maps)
        maps = [apply_columns(maps, value) for value in maps]
    costs = []
    for stage in range(low_bits):
        lane_bit = low_bits - 1 - stage if reverse else stage
        maps = all_maps[lane_bit]
        rows = [sum(((maps[bit] >> output) & 1) << bit for bit in range(32))
                for output in range(32)]
        pairs, expressions = xor_cse(rows)
        def node(index):
            return "state_%d[%d]" % (stage, index) if index < 32 else \
                "s%d_x%d" % (stage, index - 32)
        for index, (left, right) in enumerate(pairs):
            lines.append("    wire s%d_x%d = %s ^ %s;" %
                         (stage, index, node(left), node(right)))
        lines.append("    wire [31:0] jump_%d;" % stage)
        for bit, expression in enumerate(expressions):
            rhs = " ^ ".join(node(index) for index in expression) or "1'b0"
            lines.append("    assign jump_%d[%d] = %s;" % (stage, bit, rhs))
        lines.append("    wire [31:0] state_%d = lane_index[%d] ? jump_%d : state_%d;" %
                     (stage + 1, lane_bit, stage, stage))
        costs.append(len(pairs) + sum(max(0, len(row) - 1) for row in expressions))

    lines += [
        "    always @* begin",
        "        label_o = 13'd0;",
        "        if (position_i < 13)",
        "            label_o = 13'h1000 >> position_i;",
        "        else if (position_i < 4109)",
        "            label_o = state_%d[12:0];" % low_bits,
        "        else if (position_i < 4213)",
        "            label_o = PARITY_ROM[parity_index*13 +: 13];",
        "    end",
        "endmodule",
        "`default_nettype wire",
        "",
    ]
    (OUT / ("pbch_scan_label_b%s.sv" % suffix)).write_text("\n".join(lines))

    # Independently reconstruct every payload label using the split algorithm.
    for position in range(4096):
        got = states[position // block]
        for _ in range(position % block):
            got = xs(got)
        assert got & 8191 == columns[position + 13]
    return {"block": block, "reverse": reverse, "state_rom_bits": len(states) * 32,
            "parity_rom_bits": len(parity) * 13,
            "jump_xor_operations": costs, "all_payload_columns_exact": True}


def main():
    columns = CODEC.influence_columns()
    result = [generate(block, columns) for block in (16, 32, 64)]
    result.append(generate(32, columns, reverse=True))
    (OUT / "scan_label_metadata.json").write_text(json.dumps(result, indent=2) + "\n")
    golden = hex_literal(len(columns) * 13, packed(columns, 13))
    (OUT / "pbch_scan_label_b0.sv").write_text(
        "`default_nettype none\n"
        "// Original combinational table lookup, for isolated area comparison.\n"
        "module pbch_scan_label_b0(input wire [12:0] position_i,\n"
        "                          output wire [12:0] label_o);\n"
        "  localparam [%d:0] G0_COLUMNS = %s;\n"
        "  assign label_o=G0_COLUMNS[position_i*13 +: 13];\n"
        "endmodule\n`default_nettype wire\n" % (len(columns) * 13 - 1, golden))
    case_lines = ["`default_nettype none",
                  "module pbch_scan_label_bcase(input wire [12:0] position_i,",
                  "                             output reg [12:0] label_o);",
                  "  always @* begin", "    case (position_i)"]
    for index, column in enumerate(columns):
        case_lines.append("      13'd%d: label_o=13'h%04x;" % (index, column))
    case_lines += ["      default: label_o=13'd0;", "    endcase", "  end",
                   "endmodule", "`default_nettype wire", ""]
    (OUT / "pbch_scan_label_bcase.sv").write_text("\n".join(case_lines))
    lines = ["`timescale 1ns/1ps", "module scan_label_tb;",
             "  reg [12:0] position;", "  wire [12:0] label16, label32, label64, label0, labelcase, label32r;",
             "  localparam [%d:0] GOLDEN = %s;" % (len(columns) * 13 - 1, golden),
             "  pbch_scan_label_b16 u16(position,label16);",
             "  pbch_scan_label_b32 u32(position,label32);",
             "  pbch_scan_label_b64 u64(position,label64);",
             "  pbch_scan_label_b0 u0(position,label0);",
             "  pbch_scan_label_bcase ucase(position,labelcase);",
             "  pbch_scan_label_b32r u32r(position,label32r);",
             "  integer i;", "  initial begin",
             "    for (i=0;i<4213;i=i+1) begin",
             "      position=i; #1;",
             "      if (label16 !== GOLDEN[i*13 +: 13] ||",
             "          label32 !== GOLDEN[i*13 +: 13] ||",
             "          label64 !== GOLDEN[i*13 +: 13] ||",
             "          label0 !== GOLDEN[i*13 +: 13] ||",
             "          labelcase !== GOLDEN[i*13 +: 13] ||",
             "          label32r !== GOLDEN[i*13 +: 13])",
             "        $fatal(1,\"scan label mismatch at %0d\",i);",
             "    end",
             '    $display("PASS all 4213 positions for b0,b16,b32,b32r,b64,bcase");',
             "    $finish;", "  end", "endmodule", ""]
    (OUT / "scan_label_tb.sv").write_text("\n".join(lines))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
